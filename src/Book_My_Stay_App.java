/**
 * UseCase1HotelBookingApp
 *
 * This class represents the entry point for the Book My Stay
 * Hotel Booking Management System. It demonstrates how a Java
 * application starts execution using the main() method and
 * displays a welcome message to the user.
 *
 * The application prints the system name and version to the console
 * and then terminates.
 *
 * @author Student
 * @version 1.0
 */

public class UseCase1HotelBookingApp {

    /**
     * Main method - Entry point of the Java application.
     * The JVM invokes this method when the program starts.
     *
     * @param args Command line arguments
     */
    public static void main(String[] args) {

        // Display welcome message
        System.out.println("====================================");
        System.out.println(" Welcome to Book My Stay Application ");
        System.out.println(" Hotel Booking Management System ");
        System.out.println(" Version: 1.0 ");
        System.out.println("====================================");

        // Inform user that application started successfully
        System.out.println("Application started successfully.");
        System.out.println("Thank you for using Book My Stay!");
    }
}